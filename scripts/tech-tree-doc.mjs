const cap = (s) => s[0].toUpperCase() + s.slice(1);
// The GHT name when the roster has one, else the kind id capitalised.
export const labelOf = (kind) => (toasterName(kind) === kind ? cap(kind) : toasterName(kind));

// The grid cards as play/input.mjs builds them (commandCard). A key may repeat across cards (by design) but never on one card.
// Roll and Resupply sit on different cards: a selected Dart decides which one shows.
export const CARDS = Object.freeze({
  "Crumb (worker)": ["mill", "well", "toaster", "forge", "turret", "extension", "pylon", "windmill", "dam", "gather"],
  "Power Strip": ["worker", "rally", "pilot"],
  "Assembly Line": ["grunt", "lancer", "spiker", "brute", "howler", "dart", "lineRally"],
  "Mill, Well or Toaster": ["rings", "pause"],
  "Turret": ["priority"],
  "Fighters": ["resupply", "shove"],
  "Fighters with a Dart": ["roll"],
  "Box or Pylon pair": ["fence", "unplug"],
});

/** Keys that two kinds on one card share: [{ card, key, kinds }]. Reuse across different cards is not reported. */
export function clashesOnACard(keys, cards = CARDS) {
  const out = [];
  for (const [card, kinds] of Object.entries(cards)) {
    const byKey = {};
    for (const kind of kinds) if (keys[kind]) (byKey[keys[kind]] ??= []).push(kind);
    for (const [key, names] of Object.entries(byKey)) if (names.length > 1) out.push({ card, key, kinds: names });
  }
  return out;
}

const clock = (s) => `${Math.floor(s / 60)}:${String(s % 60).padStart(2, "0")}`;

// Wheat cost from ECONOMY (units and buildings), else from the stats row; "not set yet" when no row has a cost.
function costOf(kind) {
  if (kind === "claim") return `${STATS.territory.claimStructures.totem.cost} Wheat`; // a Totem or a Mound
  const e = E.units[kind] ?? E.buildings[kind];
  let cost = "";
  if (e) {
    cost = `${e.wheat} Wheat`;
    if (STATS.research.flourCost[kind]) cost += ` + ${STATS.research.flourCost[kind]} Flour`;
    return cost;
  }
  const station = E.power.stationWheat[kind] ?? E.power.energyCost[kind]; // Extension Box and Relay Pylon; Windmill and Dam
  if (station !== undefined) return `${station} Wheat`;
  if (kind === "track") return `${STATS.economy.track.costPerTile} Wheat a tile`;
  const row = kindStats(kind);
  if (!row || row.cost === undefined) return "not set yet";
  cost = row.cost && `${row.cost} Wheat`;
  if (STATS.research.flourCost[kind]) cost += ` + ${STATS.research.flourCost[kind]} Flour`;
  if (row.flux) cost += ` + ${row.flux} Flux`;
  return cost || "free";
}

// The building that trains a unit (the Power Strip trains Crumbs), else who builds a structure. Kinds with no stats row
// yet say "not set yet" rather than guess whether they are units or buildings.
function builtAt(kind) {
  if (kind === "claim") return "Crumbs build it (a Totem or a Mound)";
  if (STATS.core.trains.includes(kind)) return toasterName("core");
  const b = Object.entries(STATS.structures).find(([, s]) => s.trains?.includes(kind));
  if (b) return toasterName(b[0]);
  if (kind === "track" || kindStats(kind) || E.power.stationWheat[kind] !== undefined || E.power.energyCost[kind] !== undefined) return "Crumbs build it";
  return "not set yet";
}

const inGame = (kind) => Object.hasOwn(STATS.units, kind) || Object.hasOwn(STATS.structures, kind);

function tierSection(n) {
  const t = STATS.toasterTiers[n];
  const line = t.need ? `${t.needText}.` : "Needs nothing: open from the start.";
  const rows = t.unlocks.map((kind) => {
    const key = TOASTER_HOTKEYS[kind] ? TOASTER_HOTKEYS[kind].toUpperCase() : "-";
    return `| ${labelOf(kind)} | ${key} | ${costOf(kind)} | ${builtAt(kind)} | ${t.need ? t.needText.replace("Needs ", "") : "none"} | ${inGame(kind) ? "yes" : "not yet"} |`;
  });
  return `## Tier ${n}

${line}

| Unlock | Hotkey | Cost | Built at or by | Gate | In this build |
|---|---|---|---|---|---|
${rows.join("\n")}
`;
}

