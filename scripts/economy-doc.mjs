// Writes ECONOMY.md from env/economy-table.mjs (via ECONOMY in env/stats.mjs). `node scripts/economy-doc.mjs` writes it,
// `--check` exits 1 when the file on disk is stale. Owner: sonnet.
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import { ECONOMY as E } from "../env/stats.mjs";

const n = (x) => String(Math.round(x * 100) / 100);

export function renderEconomyDoc(e = E) {
  const pm = e.perMinute, b = e.bakery, p = e.power;
  const unitRows = Object.values(e.units).map((u) =>
    `| ${u.name} | ${u.wheat} | ${u.hp} | ${n(u.trainSeconds)} s | ${u.upkeepWheatPerMinute} | ${u.slots} | ${u.slicesPerShot} | ${u.shotDamage ?? "-"} | ${u.shotEverySeconds === null ? "-" : n(u.shotEverySeconds) + " s"} | ${u.slicesPerMinuteFighting} |`);
  const buildRows = Object.values(e.buildings).map((s) => `| ${s.name} | ${s.wheat} | ${s.hp} | ${n(s.buildSeconds)} s |`);
  const stationRows = Object.entries(e.power.stationWheat).map(([k, c]) => `| ${k} | ${c} |`);
  return `# ECONOMY.md: every number in the toaster economy

Generated by \`node scripts/economy-doc.mjs\` from \`env/economy-table.mjs\` (read it in code as \`ECONOMY\` from \`env/stats.mjs\`).
Do not edit by hand: change the number, then re-run the script. A test fails when this file is stale.

Wheat is still called "Shards" inside the code. The game runs ${e.match.ticksPerSecond} ticks a second; every time below is in seconds.

## Start of a match
- ${e.start.wheat} Wheat, ${e.start.crumbs} Crumbs, ${e.start.powerStrips} Power Strip (${e.strip.hp} hp), ${e.start.stripStack} slices of toast in its stack.
- Crumbs gather on their own. On the play page (play/idle-crumbs.mjs, hooked in play/app.mjs) an idle Crumb goes to the nearest wheat in its cord reach at the first tick, and again 3 s after it stands idle. Right-clicking wheat still overrides it.

## Wheat
- A field tile holds ${e.wheat.tileAmount} Wheat (${e.wheat.classicTileAmount} on the old Driftfall maps); a rich tile holds ${e.wheat.richMultiplier}x.
- A Crumb takes ${e.wheat.mineSeconds} s to mine a load and carries ${e.wheat.crumbCarryPerTrip} Wheat a trip (${e.wheat.classicCarryPerTrip} in a classic match). Walking time is on top.
- With six auto-gathering Crumbs on the home field, a Crumb brings about 28 Wheat a minute (about 167 for six), inside the 25-30 target, so the bank holds 400-700 after 120 s (tests/passive-income.test.mjs). The walk is short, so the mining time sets the pace.

## Units
| Unit | Wheat | HP | Train time | Upkeep (Wheat/min) | Slices held | Slices a shot | Damage | Shot every | Slices/min fighting |
|---|---|---|---|---|---|---|---|---|---|
${unitRows.join("\n")}

Upkeep is ${e.upkeep.percentOfCostPerMinute}% of a unit's cost every minute, in Wheat; Crumbs pay none. There is no supply cap (${e.match.unitCap} units is the hard limit, ${e.match.queueMax} in a queue).
A Bagel needs power but no slices.

## Buildings
| Building | Wheat | HP | Build time |
|---|---|---|---|
${buildRows.join("\n")}

## The bread chain
- **Mill:** grinds ${b.wheatPerFlour} Wheat into 1 flour every ${b.millSeconds} s.
- **Well:** ${n(60 / b.wellSeconds)} Water a minute alone (one every ${b.wellSeconds} s) by the river or creek; a spring halves it. Each other Well of any owner closer than ${b.wellCrowdRadius} tiles shares the draw: it adds (1 - d/${b.wellCrowdRadius}) to a sum and the Well draws at ${n(60 / b.wellSeconds)} / (1 + sum) a minute (two 2 tiles apart: 5.7 each). It must stand within ${b.wellReach} tiles of water and ${b.wellEnemyReach} tiles clear of enemy buildings.
- **Toaster:** every ${b.toasterSeconds} s turns 1 flour + 1 water into ${b.slicesPerBake} slices, if it is powered.
- **Pantry:** holds at most ${b.pantryCap} flour and ${b.pantryCap} water per side, plus ${b.pantryPerToaster} for each complete Toaster of that side.
- **Pilot light:** while the stack is under ${b.pilotFloor} slices, the Power Strip bakes 1 slice every ${b.pilotSeconds} s by itself.
- A Crumb carries ${e.ammo.crumbCarrySlices} slices to a fighter; the Strip keeps ${e.ammo.stripReserveSlices} slices back for emergencies.

## Power
- Cord length (tiles): ${Object.entries(e.power.cordTiles).map(([k, v]) => `${e.units[k].name} ${v}`).join(", ")}.
- Station reach (tiles): ${Object.entries(e.power.stationReachTiles).map(([k, v]) => `${k} ${v}`).join(", ")}.
- Costs (Wheat) to build a station:

| Station | Wheat |
|---|---|
${stationRows.join("\n")}

Energy (env/energy.mjs) is what powers the kitchen. Each network adds up what it makes and uses:
- **Makes:** Power Strip ${p.energyMade.strip}, Generator ${p.energyMade.generator}, Windmill ${p.energyMade.windmill} (${p.energyCost.windmill} Wheat), Dam ${p.energyMade.dam} (${p.energyCost.dam} Wheat), Mill Dam ${p.energyMade.milldam} (${p.energyCost.milldam} Wheat).
- **Uses:** each Toaster ${p.energyUsed.toaster}; each fence 1 for every ${p.fenceTilesPerEnergy} tiles, rounded up.
- **Brown-out:** when a network uses more than it makes, fences go dark first (last one first), then the newest Toaster. A Toaster on dark power does not bake.

## The math, per minute
- A **Crumb** costs ${pm.wheatPerCrumb} Wheat.
- A busy **Mill** eats ${n(pm.millWheatIn)} Wheat and makes ${n(pm.millFlourOut)} flour (worth ${n(pm.millSlicesWorth)} slices).
- A busy **Toaster** uses ${n(pm.toasterFlourIn)} flour and ${n(pm.toasterWaterIn)} water and makes ${n(pm.toasterSlicesOut)} slices. It outruns a single Mill: ${n(pm.millsPerToaster)} Mills keep one Toaster busy.
- One slice costs ${n(pm.wheatPerSlice)} Wheat (${b.wheatPerFlour} Wheat per flour, ${b.slicesPerBake} slices per flour; water is free).
- A fighting **Popper** burns ${n(pm.popperSlicesWhileFighting)} slices a minute, which is ${n(pm.popperWheatWhileFighting)} Wheat of toast a minute, plus ${n(pm.popperUpkeepWheat)} Wheat upkeep. One Popper in a fight eats the output of ${n(pm.millsToFeedOnePopper)} Mills.

## The target curve (what a match should feel like)
- **0:00-2:00, farm and kitchen.** Crumbs go to the wheat; first Mill, Well and Toaster (${e.buildings.mill.wheat + e.buildings.well.wheat + e.buildings.toaster.wheat} Wheat) by about 1:30. Six Crumbs bring about 150-180 Wheat a minute, so the first kitchen is paid for in about 1.5 minutes; flour and water are the real limit.
- **2:00-5:00, first squad.** Assembly Line, then 4-6 Poppers (${e.units.grunt.wheat} Wheat each) and a few more Crumbs. Toast, not Wheat, decides how many shots the squad has.
- **5:00+, push with boxes.** Fences and stations carry the squad forward; a second Mill per 3 Crumbs keeps the toast coming.
- **12-16 min, a typical siege.** The Power Strip has ${e.strip.hp} hp, so a fed siege takes minutes, not seconds.

## Why these numbers (value-based prices and upkeep)
- **One Mill per 3 Crumbs.** A Mill grinds ${b.wheatPerFlour} Wheat every ${b.millSeconds} s: ${n(pm.millWheatIn)} Wheat in and ${n(pm.millFlourOut)} flour (${n(pm.millSlicesWorth)} slices) out per minute. That is about a third of what 3 Crumbs bring (about 84 a minute), so two Mills keep six Crumbs' wheat moving.
- **Prices follow value.** Roughly sqrt(damage per second x hit points), then a bonus for range, splash or not needing toast: Popper ${e.units.grunt.wheat}, Zapper ${e.units.lancer.wheat} (cheaper: it is fragile and burns toast fastest), Four-Slice ${e.units.brute.wheat}, Broiler ${e.units.howler.wheat}, Flak Popper ${e.units.spiker.wheat} (nothing flies yet), Bagel ${e.units.dart.wheat} (needs power, no slices). Crumb stays ${e.units.worker.wheat}.
- **Army limit: lower upkeep, no supply cap.** Upkeep is ${e.upkeep.percentOfCostPerMinute}% of cost a minute. The other option, Supply = toast capacity, would need a new rule, a new HUD readout and new validation; the hard cap of ${e.match.unitCap} units already stops an endless swarm. One system, shown in the top bar's Upkeep per minute.
`;
}

const file = fileURLToPath(new URL("../ECONOMY.md", import.meta.url));
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = renderEconomyDoc();
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) { console.error("ECONOMY.md is stale: run node scripts/economy-doc.mjs"); process.exit(1); }
    console.log("ECONOMY.md is up to date");
  } else { fs.writeFileSync(file, text); console.log("wrote ECONOMY.md"); }
}
